#!/usr/bin/env python3
"""Reproducible pipeline benchmark on deterministic synthetic logs.

    python scripts/benchmark.py                      # 1,000 / 10,000 / 100,000 events, 3 runs each
    python scripts/benchmark.py --sizes 1000 --runs 1
    python scripts/benchmark.py --write-docs         # also (re)write docs/BENCHMARKS.md

Each size runs in a fresh subprocess so peak-memory numbers are not polluted by earlier sizes.
Measured in-process: no HTTP, no disk, no network. Results depend on the machine; the script
records the environment so numbers are comparable. Nothing here is hard-coded or estimated.
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import statistics
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

STAGES = ("parse", "redact", "normalize", "analyze", "report")


def run_single(n: int, seed: int) -> dict:
    import resource

    from app.config import DEFAULT_LIMITS
    from app.demo.synthetic import generate_plaintext
    from app.pipeline import analyze_text
    from app.reporting import render_json, render_markdown

    text = generate_plaintext(n, seed)
    size = len(text.encode("utf-8"))
    base_rss = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    timings: dict[str, float] = {}
    t0 = time.perf_counter()
    result = analyze_text(text, timings=timings)
    t1 = time.perf_counter()
    render_markdown(result)
    render_json(result)
    timings["report"] = time.perf_counter() - t1
    total = time.perf_counter() - t0
    peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    scale = 1 if sys.platform == "darwin" else 1024  # ru_maxrss: bytes on macOS, KiB on Linux
    return {
        "events": n,
        "input_bytes": size,
        "within_input_limit": size <= DEFAULT_LIMITS.max_input_bytes and n <= DEFAULT_LIMITS.max_events,
        "parsed_events": result.summary.total_events,
        "malformed": result.ingest.malformed_records,
        "redactions": sum(result.ingest.redactions.values()),
        "hypotheses": [h.category for h in result.hypotheses],
        "stage_seconds": timings,
        "total_seconds": total,
        "events_per_second": n / total if total else 0.0,
        "peak_rss_mib": peak * scale / 2**20,
        "rss_before_mib": base_rss * scale / 2**20,
    }


def environment() -> dict:
    return {
        "python": platform.python_version(),
        "implementation": platform.python_implementation(),
        "platform": platform.platform(),
        "processor": platform.processor() or platform.machine(),
        "cpu_count": os.cpu_count(),
    }


def median_run(runs: list[dict]) -> dict:
    out = dict(runs[0])
    out["runs"] = len(runs)
    out["total_seconds"] = statistics.median(r["total_seconds"] for r in runs)
    out["events_per_second"] = out["events"] / out["total_seconds"]
    out["stage_seconds"] = {k: statistics.median(r["stage_seconds"][k] for r in runs) for k in runs[0]["stage_seconds"]}
    out["peak_rss_mib"] = max(r["peak_rss_mib"] for r in runs)
    return out


def table(results: list[dict]) -> str:
    head = "| Events | Input (MiB) | Runs | " + " | ".join(f"{s} (s)" for s in STAGES) + " | Total (s) | Events/s | Peak RSS (MiB) |"
    sep = "| ---: | ---: | ---: | " + " | ".join("---:" for _ in STAGES) + " | ---: | ---: | ---: |"
    rows = [
        f"| {r['events']:,} | {r['input_bytes'] / 2**20:.2f} | {r['runs']} | "
        + " | ".join(f"{r['stage_seconds'][s]:.3f}" for s in STAGES)
        + f" | {r['total_seconds']:.3f} | {r['events_per_second']:,.0f} | {r['peak_rss_mib']:.0f} |"
        for r in results
    ]
    return "\n".join([head, sep, *rows])


def write_docs(results: list[dict], env: dict, seed: int) -> None:
    text = f"""# Benchmarks

Generated by `python backend/scripts/benchmark.py --write-docs` (seed {seed}). These are **measured** results from
one run of the script on the machine below, not estimates. Re-run the script on your own hardware.

## Environment

```json
{json.dumps(env, indent=2)}
```

## Results (median of N runs; peak RSS is the maximum over runs)

{table(results)}

Stage meanings: `parse` includes the input-size check and format detection; `report` is Markdown + JSON rendering.
Benchmarks cover the in-process pipeline only (no HTTP transfer, JSON serialization of the API response, or browser rendering).

## Input limits that apply

- Max decoded input: 20 MiB (`INCIDENTLENS_MAX_INPUT_BYTES`)
- Max records: 100,000 (`INCIDENTLENS_MAX_EVENTS`); larger inputs are rejected, never truncated.

Synthetic input: mostly INFO request lines plus background warnings/errors and a mid-window error burst; every 50th
line contains a fake secret so redaction does real work. See `backend/app/demo/synthetic.py`.
"""
    (ROOT.parent / "docs" / "BENCHMARKS.md").write_text(text, encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--sizes", type=int, nargs="+", default=[1_000, 10_000, 100_000])
    ap.add_argument("--runs", type=int, default=3)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--single", type=int, help=argparse.SUPPRESS)
    ap.add_argument("--write-docs", action="store_true")
    args = ap.parse_args()

    if args.single:
        print(json.dumps(run_single(args.single, args.seed)))
        return 0

    results = []
    for n in args.sizes:
        runs = []
        for _ in range(args.runs):
            proc = subprocess.run([sys.executable, __file__, "--single", str(n), "--seed", str(args.seed)],
                                  capture_output=True, text=True, check=False)
            if proc.returncode != 0:
                print(proc.stderr, file=sys.stderr)
                return proc.returncode
            runs.append(json.loads(proc.stdout))
        r = median_run(runs)
        if not r["within_input_limit"]:
            print(f"warning: {n:,} events exceed the documented input limits", file=sys.stderr)
        results.append(r)
    env = environment()
    print(json.dumps(env))
    print(table(results))
    if args.write_docs:
        write_docs(results, env, args.seed)
        print("wrote docs/BENCHMARKS.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

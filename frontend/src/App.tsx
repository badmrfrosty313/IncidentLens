import { useCallback, useEffect, useRef, useState } from "react";
import ErrorFrequencyChart from "./components/ErrorFrequencyChart";
import ExpectedOutcomeCard from "./components/ExpectedOutcomeCard";
import ExportButtons from "./components/ExportButtons";
import FindingsPanel from "./components/FindingsPanel";
import Header from "./components/Header";
import type { ApiStatus } from "./components/Header";
import HypothesisList from "./components/HypothesisList";
import IngestPanel from "./components/IngestPanel";
import InvestigationSteps from "./components/InvestigationSteps";
import LogViewer from "./components/LogViewer";
import SeverityChart from "./components/SeverityChart";
import StatCards from "./components/StatCards";
import TimelineChart from "./components/TimelineChart";
import { analyze, getHealth, listScenarios, runScenario } from "./lib/api";
import type { TimeWindow } from "./lib/filters";
import { INCIDENT_STYLE, VERDICT_LABEL } from "./lib/format";
import { REPO_URL, isStaticDemo } from "./lib/mode";
import type { AnalysisResponse, AnalysisSource, FormatHint, ScenarioInfo } from "./types/api";

export default function App() {
  const [status, setStatus] = useState<ApiStatus>("checking");
  const [version, setVersion] = useState<string>();
  const [scenarios, setScenarios] = useState<ScenarioInfo[]>([]);
  const [analysis, setAnalysis] = useState<AnalysisResponse | null>(null);
  const [source, setSource] = useState<AnalysisSource | null>(null);
  const [activeScenario, setActiveScenario] = useState<ScenarioInfo | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [timeWindow, setTimeWindow] = useState<TimeWindow | null>(null);
  const requestId = useRef(0);

  useEffect(() => {
    let cancelled = false;
    getHealth()
      .then((h) => {
        if (!cancelled) {
          setStatus(h.status === "static" ? "static" : "online");
          setVersion(h.version);
        }
      })
      .catch(() => !cancelled && setStatus("offline"));
    listScenarios()
      .then((s) => !cancelled && setScenarios(s))
      .catch(() => undefined);
    return () => {
      cancelled = true;
    };
  }, []);

  /** Runs a request, ignoring the result if a newer one was started meanwhile. */
  const run = useCallback(async (task: (isCurrent: () => boolean) => Promise<void>) => {
    const id = ++requestId.current;
    const isCurrent = () => id === requestId.current;
    setBusy(true);
    setError(null);
    try {
      await task(isCurrent);
    } catch (e) {
      if (isCurrent()) setError(e instanceof Error ? e.message : "Analysis failed.");
    } finally {
      if (isCurrent()) setBusy(false);
    }
  }, []);

  const handleScenario = useCallback(
    (scenarioId: string) =>
      void run(async (isCurrent) => {
        const res = await runScenario(scenarioId);
        if (!isCurrent()) return;
        setAnalysis(res.analysis);
        setActiveScenario(res.scenario);
        setSource({ kind: "demo", scenarioId });
        setTimeWindow(null);
      }),
    [run],
  );

  const handleAnalyze = useCallback(
    (content: string, format: FormatHint, label: string) =>
      void run(async (isCurrent) => {
        const res = await analyze(content, format);
        if (!isCurrent()) return;
        setAnalysis(res);
        setActiveScenario(null);
        setSource({ kind: "content", content, format, label });
        setTimeWindow(null);
      }),
    [run],
  );

  return (
    <div className="min-h-screen">
      <Header status={status} version={version} />
      {isStaticDemo() && (
        <div role="note" data-testid="static-demo-banner" className="border-b border-amber-400/30 bg-amber-400/10 px-4 py-2 text-center text-sm text-amber-200">
          <strong>Static demonstration.</strong> Pre-computed results for seven synthetic scenarios, generated by the Python analysis engine at build time.
          Uploads and manual analysis are disabled.{" "}
          <a className="underline" href={REPO_URL} target="_blank" rel="noopener noreferrer">
            Run the full application locally
          </a>
          .
        </div>
      )}
      {status === "offline" && (
        <div role="alert" className="border-b border-rose-500/30 bg-rose-500/10 px-4 py-2 text-center text-sm text-rose-300">
          The IncidentLens API is not reachable. Start the backend (see README) and reload.
        </div>
      )}
      <main className="mx-auto grid max-w-[1600px] grid-cols-1 gap-4 p-4 lg:grid-cols-[340px_minmax(0,1fr)]">
        <aside className="min-w-0 space-y-4">
          <IngestPanel
            scenarios={scenarios}
            busy={busy}
            activeScenarioId={activeScenario?.id ?? null}
            onAnalyze={handleAnalyze}
            onSelectScenario={handleScenario}
          />
          {analysis && activeScenario && <ExpectedOutcomeCard scenario={activeScenario} analysis={analysis} />}
        </aside>

        <section className="min-w-0 space-y-4" aria-live="polite" aria-busy={busy}>
          {error && (
            <div role="alert" className="rounded-md border border-rose-500/40 bg-rose-500/10 px-3 py-2 text-sm text-rose-300">
              {error}
            </div>
          )}

          {!analysis && !error && (
            <div className="panel flex flex-col items-center justify-center gap-2 px-6 py-24 text-center">
              <h2 className="text-lg font-semibold text-white">{busy ? "Analyzing…" : "Turn raw logs into an incident report"}</h2>
              <p className="max-w-md text-sm text-slate-400">
                {isStaticDemo()
                  ? "Pick one of the seven demo scenarios to explore a pre-computed analysis."
                  : "Pick a demo scenario, upload a log file, or paste log lines. Plaintext, JSON and JSONL are detected automatically."}
              </p>
            </div>
          )}

          {analysis && (
            <>
              <div className="flex flex-wrap items-center justify-between gap-3">
                <div className="flex items-center gap-3">
                  <span className={`rounded border px-2 py-1 text-xs font-semibold uppercase tracking-wide ${INCIDENT_STYLE[analysis.summary.incident_severity]}`}>
                    {VERDICT_LABEL[analysis.verdict]}
                  </span>
                  <p className="text-sm text-slate-400">{analysis.verdict_reason}</p>
                </div>
                <ExportButtons source={source} />
              </div>

              <StatCards analysis={analysis} />

              <div className="grid gap-4 xl:grid-cols-3">
                <div className="xl:col-span-2">
                  <TimelineChart analysis={analysis} selected={timeWindow} onSelect={setTimeWindow} />
                </div>
                <SeverityChart distribution={analysis.summary.severity_distribution} />
              </div>

              <div className="grid gap-4 xl:grid-cols-2">
                <ErrorFrequencyChart groups={analysis.groups} />
                <FindingsPanel analysis={analysis} />
              </div>

              <div className="grid gap-4 xl:grid-cols-[minmax(0,3fr)_minmax(0,2fr)]">
                <HypothesisList analysis={analysis} />
                <InvestigationSteps steps={analysis.recommended_steps} />
              </div>

              <LogViewer
                events={analysis.events}
                total={analysis.events_total}
                truncated={analysis.events_truncated}
                window={timeWindow}
                onClearWindow={() => setTimeWindow(null)}
              />
            </>
          )}
        </section>
      </main>
      <footer className="mx-auto max-w-[1600px] px-4 pb-8 text-xs text-slate-600">
        Evidence scores are heuristic ranking aids, not probabilities. Redaction is pattern-based and best-effort: review exported reports before sharing.
      </footer>
    </div>
  );
}
